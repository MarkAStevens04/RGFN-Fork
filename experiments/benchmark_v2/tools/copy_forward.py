#!/usr/bin/env python
"""Copy clean v1 training cells into the benchmark_v2 tree, with provenance.

WHY A TOOL AND NOT ``cp -r``. Three of this copy's requirements are invisible if you get them wrong,
and all three were learned the expensive way:

1. **The real trace is often not the file named ``trace.csv``.** Re-invoking a runner truncates it to
   its 59-byte header while the full history survives as ``trace.csv.1`` -- the defect `3281bce`
   fixed by making TraceWriter rotate. Nine cells are in that state. ``cp trace.csv`` carries the
   stub, ``manifest.py`` then correctly reports ``no-trace`` for a cell whose history we still hold,
   and Stage 2 pays to re-sample a pool it could have harvested free (``saturn_clpp/s42``: 500 modes
   from history alone, 28 GPU-h -> 0). So the trace is RESOLVED and lands as ``trace.csv`` in v2.

2. **``fixed_reward/`` is no longer the arm-A artifact on 44 of 54 cells.** Stage 2 snapshots it to
   ``fixed_reward.budget_faithful/`` before upsampling, and the live directory now holds 4,000-16,438
   rows against the snapshot's 2,000. Taking the live one ships an upsampled pool as if it were the
   training sample. The snapshot wins where it exists; which one was taken is recorded in the ledger
   note, because the difference is invisible downstream.

3. **All ten milestone checkpoints travel.** Decided 2026-09-07: the logging spec adopted them as
   "cheap insurance ... so any per-step analysis we did not anticipate can be redone by resampling
   rather than retraining". 95 GB against 28 TB of scratch is 0.3%, and the asymmetry is total -- a
   milestone dropped today cannot be recovered without retraining the cell.

WHAT IT WRITES, AND WHERE. The v2 path contract is ``manifest.py``'s, not this file's:
``$BENCHMARK_V2_SCRATCH/train/<generator>_<target>_s<seed>/arm<a>/``. Writing to any other shape
would leave manifest unable to see the copy, so the destination is computed by importing manifest
rather than by rebuilding the path here.

Each copied cell also gets ``.copy_manifest.json`` -- every file with its size and md5, plus which
candidates directory and which trace file were chosen. That is DESTINATION integrity, and it is
deliberately separate from the ledger's ``source_md5``, which is a digest of the v1 SOURCE and
answers a different question (has the thing we copied from changed since?).

IDEMPOTENT. A cell whose destination already holds a matching ``.copy_manifest.json`` is skipped, so
an interrupted run resumes rather than restarts, and re-running is safe.

    python experiments/benchmark_v2/tools/copy_forward.py                 # DRY RUN, the default
    python experiments/benchmark_v2/tools/copy_forward.py --execute
    python experiments/benchmark_v2/tools/copy_forward.py --execute --cell s3gfn/seh/44
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from inventory_v1_cells import (  # noqa: E402
    CKPT_GLOBS,
    COMPETITORS,
    SEEDS,
    TARGETS,
    best_trace,
    inspect,
    run_dir,
)

# Verdicts that produce a copy. `resample` is deliberately included: the cell's POOL is missing but
# its checkpoints and trace are intact, so everything except candidates/ travels now and the pool is
# regenerated by sampling the frozen policy -- minutes, against the GPU-days a re-train would cost.
COPYABLE = {"copy", "attention", "resample"}

# What a training cell consists of. Anything not listed is left behind on purpose: `fixed_reward/`
# (post-Stage-2, superseded by the snapshot), tb_logs, and the generator's own scratch.
#
# TWO TANGO EXCLUSIONS, AND THEY ARE NOT THE SAME DECISION:
#   syntheseus_results/  4.1 GB/cell. ARM 1 -- the in-loop route dumps, keyed by oracle call. The
#                        project RETIRED this arm: its coverage correlates with the generator's own
#                        mode collapse (7 of 218 molecules on the pruned sEH pool), so it cannot even
#                        spend a 100-reaction budget. Dropped deliberately; ~37 GB saved across 9 cells.
#   pool_syntheseus/     903 MB/cell. ARM 2 -- routes over the EMITTED POOL, which IS the arm we use.
#                        NOT dropped on the merits: it is a stage-3 artifact and this tool copies
#                        stage `train`, so putting it under train/ would muddle the layout. It is
#                        worth ~3.5 h/cell of syntheseus to regenerate (~31 GPU-h over 9 cells), so
#                        it should be carried into routes/ by whoever owns stage 3 rather than lost.
#                        Flagged to the coordinator; do not let it fall between the two stages.
TOP_FILES = ("run_config.yaml", "run_config_effective.yaml", "timing.json",
             "staged_learning.toml", "sampling.toml", "saturn.log",
             "oracle_history.csv", "staged_learning_1.csv")


def _md5(p: Path) -> str:
    h = hashlib.md5()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _final_checkpoint(rels: list[str]) -> str | None:
    """Which of a cell's checkpoints is the TRAINED one, as a destination-relative path.

    Generators disagree on naming, so this is a documented heuristic rather than a lookup: prefer a
    name saying so (``final``/``last``), else one carrying no step number (REINVENT's ``agent.chkpt``
    beside its ``agent_step112.chkpt`` milestones; S3-GFN's ``..._model.pt`` beside ``..._step64_``),
    else the highest step number. The choice is RECORDED in arm_meta.json rather than left implicit,
    so a wrong guess is visible instead of silently sampling a mid-training snapshot.
    """
    if not rels:
        return None
    named = [r for r in rels if re.search(r"final|last", r, re.I)]
    if named:
        return sorted(named)[0]
    unstepped = [r for r in rels if not re.search(r"step\d+", r, re.I)]
    if unstepped:
        return sorted(unstepped, key=len)[0]
    def step(r):
        m = re.search(r"step(\d+)", r, re.I)
        return int(m.group(1)) if m else -1
    return max(rels, key=step)


def plan_cell(gen: str, target: str, seed: int) -> dict | None:
    """Everything to copy for one cell, as (source, destination-relative) pairs. None if not copyable."""
    rec = inspect(gen, target, seed)
    if rec["verdict"] not in COPYABLE:
        return None
    src = run_dir(gen, target, seed)
    pairs: list[tuple[Path, str]] = []
    notes: list[str] = []

    # -- 1. the trace, RESOLVED --------------------------------------------------------------
    t = best_trace(src)
    if t and (t.get("n_scored") or 0) > 0:
        tf = src / t["source"]
        pairs.append((tf, "trace.csv"))
        if t["source"] != "trace.csv":
            notes.append(f"trace RECOVERED from {t['source']} (trace.csv was a truncated stub)")
    else:
        notes.append("NO USABLE TRACE — stage 2 loses its free-pool harvest for this cell "
                     "and must sample the checkpoint instead (a cost, not a correctness failure)")

    # -- 2. the candidates, SNAPSHOT-FIRST ---------------------------------------------------
    snap = src / "fixed_reward.budget_faithful" / "candidates"
    live = src / "fixed_reward" / "candidates"
    chosen = snap if (snap / "candidates.csv").is_file() else live
    if (chosen / "candidates.csv").is_file():
        for f in sorted(chosen.iterdir()):
            if f.is_file():
                pairs.append((f, f"fixed_reward/candidates/{f.name}"))
        which = "budget_faithful snapshot" if chosen is snap else "fixed_reward (no snapshot)"
        notes.append(f"candidates from {which}")
    else:
        notes.append("NO candidates.csv — pool must be regenerated by re-SAMPLING the frozen "
                     "policy (checkpoints and trace survive; this is not a re-train)")

    # -- 3. every checkpoint, via the SAME globs the inventory counts with ---------------------
    # ONE DEFINITION OF "WHERE THIS GENERATOR'S WEIGHTS LIVE". An earlier version walked a list of
    # checkpoint DIRECTORIES instead, and silently dropped every top-level checkpoint: REINVENT keeps
    # its FINAL agent at `agent.chkpt` in the run root and only its milestones under checkpoints/, so
    # all nine REINVENT cells copied the step snapshots and left behind the trained weights Stage 2
    # would actually sample. The inventory's CKPT_GLOBS already knew about it; the copy did not.
    # Two definitions of the same thing is how that happens, so now there is one.
    ckpts = []
    for g in CKPT_GLOBS.get(gen, []):
        ckpts += [f for f in sorted(src.glob(g)) if f.is_file()]
    for f in ckpts:
        rel = f.relative_to(src)
        # Flatten top-level weights into checkpoints/ so every cell has one predictable home.
        pairs.append((f, str(rel) if rel.parent.name else f"checkpoints/{f.name}"))
    notes.append(f"{len(ckpts)} checkpoint file(s) — ALL milestones travel (logging-spec decision)")

    # -- 4. config and provenance-bearing logs -----------------------------------------------
    for name in TOP_FILES:
        f = src / name
        if f.is_file():
            pairs.append((f, name))

    return {"gen": gen, "target": target, "seed": seed, "src": src, "pairs": pairs,
            "notes": notes, "verdict": rec["verdict"], "why": rec["why"],
            "n_bytes": sum(s.stat().st_size for s, _ in pairs)}


def do_copy(plan: dict, dest: Path, execute: bool) -> dict:
    """Copy, then re-hash every landed file. Returns the destination manifest."""
    files = {}
    for s, rel in plan["pairs"]:
        d = dest / rel
        if execute:
            d.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(s, d)
            got = _md5(d)
            if got != _md5(s):  # a truncated copy is silent; catch it here, not in Stage 2
                raise RuntimeError(f"copy verify FAILED for {s} -> {d}")
        else:
            got = ""
        files[rel] = {"src": str(s), "bytes": s.stat().st_size, "md5": got}
    manifest = {
        "cell": f"{plan['gen']}_{plan['target']}_s{plan['seed']}",
        "source_run_dir": str(plan["src"]),
        "verdict": plan["verdict"], "why": plan["why"],
        "notes": plan["notes"], "n_files": len(files), "n_bytes": plan["n_bytes"],
        "files": files,
    }
    if execute:
        (dest / ".copy_manifest.json").write_text(json.dumps(manifest, indent=2))
        _write_arm_meta(plan, dest, files)
    return manifest


def _write_arm_meta(plan: dict, dest: Path, files: dict) -> None:
    """The contract `verify_cell.py` enforces -- and it means something different for a COPIED cell.

    For a GENERATED arm-A cell, agent A's checkpointer fires mid-run at the 10,000-call crossing and
    records where it fired. A copied competitor cell has no crossing: the run ENDED at its budget, so
    its final weights ARE the arm-A weights by construction. Same field, different provenance, and
    the difference is recorded rather than smoothed over -- `origin` and `provenance` say which case
    this is, so nobody later reads a copied cell as evidence that a checkpointer ran.

    ``n_scored_at_checkpoint`` is read from the TRACE (count of phase=="train" rows), never computed
    as batch x steps -- replay handling differs per generator and S3-GFN interleaves an eval sample,
    so the counter is not the budget.
    """
    t = best_trace(plan["src"]) or {}
    ckpts = [r for r in files if r.startswith(("checkpoints/", "population_checkpoints/"))]
    meta = {
        "arm": "a",
        "budget_calls": 10_000,
        "n_scored_at_checkpoint": t.get("train_rows") or t.get("n_scored"),
        "checkpoint": _final_checkpoint(ckpts),
        "n_checkpoints": len(ckpts),
        "generator": plan["gen"],
        "target": plan["target"],
        "seed": plan["seed"],
        "origin": "copied",
        "provenance": ("copied from a v1 run that ENDED at the arm-A budget, so its final weights are "
                       "the arm-A checkpoint by construction -- no mid-run crossing was recorded"),
        "source_run_dir": str(plan["src"]),
        "trace_source": t.get("source"),
        "verdict": plan["verdict"],
    }
    (dest / "arm_meta.json").write_text(json.dumps(meta, indent=2))


def plan_arm2_routes(gen: str, target: str, seed: int) -> dict | None:
    """TANGO's ARM-2 routes: syntheseus run over the EMITTED POOL, a stage-`routes` artifact.

    WHY IT IS COPIED HERE RATHER THAN LEFT FOR STAGE 3. We already hold it, regenerating costs ~3.5 h
    of syntheseus per cell, and an artifact that belongs to neither agent's scope is exactly how 900 MB
    goes missing between two of them. It lands under ``routes/``, NOT ``train/`` -- the stage it
    actually belongs to.

    WHY ``full_pool``, AND WHY IT IS A CONTRACT SHAPE RATHER THAN A LABEL COINED FOR TANGO. The
    dividing line is whether routes can be SUBSET, and it splits the entrants cleanly in two:

      route-NATIVE (SynFormer, TANGO)   syntheseus searches each target INDEPENDENTLY, so routes over
                                        the full emitted pool genuinely contain the routes for any
                                        subset of it. Route the pool ONCE, subset per variant at read
                                        time. `full_pool` is both correct and cheaper.
      route-PLANNED (FragGFN, S3-GFN,   MultiAiZ is SET-BASED: planning 500 diverse molecules
      REINVENT, Saturn)                 converges on different shared intermediates than planning 500
                                        near-duplicates, so a naive run is NOT a subset of a larger
                                        one and never can be. Those need
                                        ``routes/<tag>/arm<a>/{naive,pruned}`` planned separately.

    So filing this under ``naive`` or ``pruned`` would mislabel a pool-agnostic artifact, and filing it
    under both would duplicate 900 MB while asserting two artifacts exist where there is one.

    SCOPE, measured: exactly ONE cell has this -- tango_seh/seed42, 2,000 targets. Not all nine.

    Its config is the FAIR one (``num_top_results: 5``, not the authors' search-crippling 1; MEGAN;
    the authors' frag-reac-zinc-stock inventory; ``time_limit_s`` 180). That is a provenance question
    review will ask: the project deliberately runs TANGO at its best case and discloses the deviation,
    because publishing a 20% solve rate obtained under a setting we could see was crippling would read
    as sandbagging. These routes were produced under that setting, so they are usable as-is.

    NOT to be confused with ``syntheseus_results/`` in the same run dir -- that is ARM 1, retired
    because its coverage tracks the generator's own mode collapse, and it is deliberately dropped.
    """
    src = run_dir(gen, target, seed) / "pool_syntheseus"
    if not (src / "targets.smi").is_file():
        return None
    pairs = [(f, str(f.relative_to(src))) for f in sorted(src.rglob("*")) if f.is_file()]
    n_targets = sum(1 for _ in open(src / "targets.smi"))
    return {
        "gen": gen, "target": target, "seed": seed, "src": src, "pairs": pairs,
        "verdict": "copy", "why": f"ARM 2 syntheseus routes over {n_targets:,} emitted-pool molecules",
        "notes": [
            f"ARM 2 — syntheseus routes over the FULL emitted pool ({n_targets:,} molecules), so this "
            f"is a superset of the naive and pruned variants; SUBSET it, do not regenerate",
            "config is the fair one: num_top_results=5 (not the authors' 1), MEGAN, authors' stock",
            "ARM 1 (syntheseus_results/) deliberately NOT copied — retired, its coverage tracks the "
            "generator's own mode collapse",
        ],
        "n_bytes": sum(s.stat().st_size for s, _ in pairs),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--execute", action="store_true",
                    help="actually copy (default is a dry run that moves nothing)")
    ap.add_argument("--cell", help="restrict to one gen/target/seed, e.g. s3gfn/seh/44")
    ap.add_argument("--quick-digest", action="store_true",
                    help="ledger source_md5 uses mtime not content (~100x faster; smoke only)")
    ap.add_argument("--no-ledger", action="store_true", help="skip the ledger append")
    a = ap.parse_args()

    try:
        import manifest as v2manifest
    except ImportError:
        sys.exit("manifest.py not found in tools/ — it defines the v2 path contract and is agent C's "
                 "file. Merge C's branch before running this.")
    ledger = None
    if not a.no_ledger:
        try:
            import ledger as ledger_mod
            ledger = ledger_mod
        except ImportError:
            sys.exit("ledger.py not found in tools/ (agent C's). Re-run with --no-ledger to plan "
                     "without recording, or merge C's branch.")

    # Cells come from C's loader, not a list rebuilt here: grid.csv is the campaign's authoritative
    # cell list and load_grid() is how every other driver reads it. Rebuilding the enumeration would
    # be a second definition that silently diverges the first time the grid changes.
    by_key = {(c.generator, c.target_name, c.seed): c for c in v2manifest.load_grid()}
    cells = [(g, t, s) for g in COMPETITORS for t in TARGETS for s in SEEDS]
    if a.cell:
        g, t, s = a.cell.split("/")
        cells = [(g, t, int(s))]

    total_bytes = n_copied = n_skipped = 0
    print("DRY RUN — nothing is copied. Re-run with --execute.\n" if not a.execute else "")
    for gen, target, seed in cells:
        plan = plan_cell(gen, target, seed)
        tag = f"{gen}_{target}_s{seed}"
        if plan is None:
            continue
        cell = by_key.get((gen, target, seed))
        if cell is None:
            print(f"{tag:<26} SKIP — not in grid.csv (is the grid regenerated?)")
            continue
        dest = cell.train_dir("a")
        # IDEMPOTENCY IS A CONTENT CHECK, NOT AN EXISTENCE CHECK -- the runbook's own one-line rule.
        # An earlier version skipped any cell that had a .copy_manifest.json, which meant a cell
        # copied under a buggy plan stayed broken forever: the nine REINVENT cells whose final
        # agent.chkpt was never copied would have been skipped by the very run that fixed the bug.
        # So a cell is skipped only when it already holds EVERY file the current plan names, plus
        # arm_meta.json.
        want = {rel for _, rel in plan["pairs"]}
        have = (
            {str(f.relative_to(dest)) for f in dest.rglob("*") if f.is_file()}
            if dest.is_dir()
            else set()
        )
        if (dest / "arm_meta.json").is_file() and not (want - have):
            n_skipped += 1
            continue
        missing = sorted(want - have)
        if have and missing:
            print(
                f"{tag:<26} REFRESH — {len(missing)} file(s) missing from an earlier copy: "
                f"{', '.join(missing[:3])}{' ...' if len(missing) > 3 else ''}"
            )
        m = do_copy(plan, dest, a.execute)
        total_bytes += m["n_bytes"]
        n_copied += 1
        print(f"{tag:<26} {m['n_files']:>4} files  {m['n_bytes']/1e9:>7.2f} GB  -> {dest}")
        for note in m["notes"]:
            print(f"    · {note}")
        if a.execute and ledger is not None:
            digest, nf, nb = ledger.tree_digest(plan["src"], quick=a.quick_digest)
            ledger.record(
                stage="train", generator=gen, target=target, seed=seed, arm="a",
                origin="copied", source_path=str(plan["src"]), source_md5=digest,
                note="; ".join(m["notes"]),
            )

    print(f"\n{n_copied} cell(s) {'copied' if a.execute else 'to copy'}, "
          f"{n_skipped} already present, {total_bytes/1e9:.1f} GB total")

    # -- stage `routes`: TANGO's ARM-2 syntheseus output, where it exists --------------------
    print("\nstage routes — ARM 2 (TANGO):")
    found = 0
    for gen, target, seed in cells:
        rp = plan_arm2_routes(gen, target, seed)
        if rp is None:
            continue
        found += 1
        cell = by_key.get((gen, target, seed))
        dest = cell.routes_dir("a", "full_pool") if cell else None
        if dest is None:
            print("  not in grid.csv — skipped")
            continue
        if (dest / ".copy_manifest.json").is_file():
            print(f"  {cell.tag} already present")
            continue
        m = do_copy(rp, dest, a.execute)
        print(f"  {cell.tag:<22} {m['n_files']:>5} files  {m['n_bytes']/1e9:>6.2f} GB  -> {dest}")
        for note in m["notes"]:
            print(f"      · {note}")
        if a.execute:
            (dest / "README.md").write_text(
                "# TANGO ARM-2 routes — the FULL emitted pool\n\n"
                + "\n".join(f"- {n}" for n in m["notes"]) + "\n\n"
                f"Copied from `{rp['src']}` by `tools/copy_forward.py`.\n"
                "Filed under `full_pool` rather than `naive`/`pruned` because it covers all\n"
                "2,000 emitted molecules — a superset of both variants.\n"
            )
            if ledger is not None:
                digest, _, _ = ledger.tree_digest(rp["src"], quick=a.quick_digest)
                ledger.record(stage="routes", generator=gen, target=target, seed=seed, arm="a",
                              origin="copied", source_path=str(rp["src"]), source_md5=digest,
                              note="; ".join(m["notes"]))
    if not found:
        print("  none found")
    return 0


if __name__ == "__main__":
    sys.exit(main())
